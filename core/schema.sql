BEGIN IMMEDIATE;
CREATE TABLE rooms(scope TEXT PRIMARY KEY, platform TEXT NOT NULL, owner TEXT NOT NULL, room TEXT NOT NULL,
 name TEXT NOT NULL DEFAULT '', paused INTEGER NOT NULL DEFAULT 0, epoch INTEGER NOT NULL DEFAULT 0,
 cursor INTEGER NOT NULL DEFAULT 0, last_auto INTEGER NOT NULL DEFAULT 0);
CREATE TABLE messages(id INTEGER PRIMARY KEY AUTOINCREMENT, scope TEXT NOT NULL REFERENCES rooms(scope),
 message_id TEXT NOT NULL, sender TEXT NOT NULL, text TEXT NOT NULL, at INTEGER NOT NULL,
 kind TEXT NOT NULL, reply TEXT NOT NULL DEFAULT '', mentions TEXT NOT NULL DEFAULT '[]',
 disclosure TEXT NOT NULL DEFAULT 'private', UNIQUE(scope,message_id));
CREATE INDEX messages_scope ON messages(scope,id);
CREATE TABLE aliases(id TEXT PRIMARY KEY, scope TEXT NOT NULL REFERENCES rooms(scope), member TEXT NOT NULL,
 name TEXT NOT NULL, kind TEXT NOT NULL, source TEXT NOT NULL, status TEXT NOT NULL,
 first_at INTEGER NOT NULL, last_at INTEGER NOT NULL, revision INTEGER NOT NULL DEFAULT 1,
 UNIQUE(scope,member,name,kind));
CREATE TABLE alias_versions(id INTEGER PRIMARY KEY, alias_id TEXT NOT NULL REFERENCES aliases(id) ON DELETE CASCADE,
 revision INTEGER NOT NULL, previous TEXT NOT NULL, actor TEXT NOT NULL, at INTEGER NOT NULL);
CREATE TABLE preferences(scope TEXT NOT NULL REFERENCES rooms(scope), member TEXT NOT NULL, opted_out INTEGER NOT NULL,
 PRIMARY KEY(scope,member));
CREATE TABLE permissions(platform TEXT NOT NULL, owner TEXT NOT NULL, member TEXT NOT NULL, room TEXT NOT NULL,
 allowed INTEGER NOT NULL, PRIMARY KEY(platform,owner,member,room));
CREATE TABLE claims(id TEXT PRIMARY KEY, scope TEXT NOT NULL REFERENCES rooms(scope), subject TEXT NOT NULL DEFAULT '',
 content TEXT NOT NULL, purpose TEXT NOT NULL, reason TEXT NOT NULL DEFAULT '', attribution TEXT NOT NULL,
 status TEXT NOT NULL, restricted INTEGER NOT NULL DEFAULT 0, origin TEXT NOT NULL,
 event_id TEXT REFERENCES events(id), valid_until INTEGER, revision INTEGER NOT NULL DEFAULT 1,
 created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL);
CREATE INDEX claims_scope ON claims(scope,subject,status);
CREATE TABLE events(id TEXT PRIMARY KEY, scope TEXT NOT NULL REFERENCES rooms(scope), title TEXT NOT NULL,
 content TEXT NOT NULL, at INTEGER NOT NULL, status TEXT NOT NULL DEFAULT 'active', revision INTEGER NOT NULL DEFAULT 1);
CREATE TABLE evidence(claim_id TEXT NOT NULL REFERENCES claims(id) ON DELETE CASCADE,
 raw_id INTEGER NOT NULL REFERENCES messages(id) ON DELETE CASCADE, start INTEGER NOT NULL, end INTEGER NOT NULL,
 PRIMARY KEY(claim_id,raw_id,start,end));
CREATE TABLE event_evidence(event_id TEXT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
 raw_id INTEGER NOT NULL REFERENCES messages(id) ON DELETE CASCADE, PRIMARY KEY(event_id,raw_id));
CREATE TABLE versions(id INTEGER PRIMARY KEY, scope TEXT NOT NULL, entity TEXT NOT NULL, entity_id TEXT NOT NULL,
 revision INTEGER NOT NULL, previous TEXT NOT NULL, actor TEXT NOT NULL, at INTEGER NOT NULL);
CREATE TABLE links(id TEXT PRIMARY KEY, scope TEXT NOT NULL, source TEXT NOT NULL REFERENCES claims(id) ON DELETE CASCADE,
 target TEXT NOT NULL REFERENCES claims(id) ON DELETE CASCADE, kind TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending',
 UNIQUE(source,target,kind));
CREATE TABLE tasks(id TEXT PRIMARY KEY, scope TEXT NOT NULL REFERENCES rooms(scope), kind TEXT NOT NULL,
 member TEXT NOT NULL DEFAULT '', status TEXT NOT NULL, preview INTEGER NOT NULL, cursor INTEGER NOT NULL,
 end_id INTEGER NOT NULL, offset INTEGER NOT NULL DEFAULT 0, processed INTEGER NOT NULL DEFAULT 0,
 attempts INTEGER NOT NULL DEFAULT 0, result TEXT NOT NULL DEFAULT '{}', error TEXT NOT NULL DEFAULT '{}',
 epoch INTEGER NOT NULL, created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL);
CREATE UNIQUE INDEX one_running_group ON tasks(scope) WHERE status='running';
CREATE TABLE progress(scope TEXT NOT NULL, member TEXT NOT NULL, cursor INTEGER NOT NULL,
 offset INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(scope,member));
CREATE TABLE deferred(scope TEXT NOT NULL, raw_id INTEGER NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
 reason TEXT NOT NULL, attempts INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(scope,raw_id));
CREATE TABLE calls(id TEXT PRIMARY KEY, task_id TEXT NOT NULL REFERENCES tasks(id), scope TEXT NOT NULL,
 day TEXT NOT NULL, status TEXT NOT NULL, provider TEXT NOT NULL, input INTEGER NOT NULL, output INTEGER NOT NULL,
 estimated INTEGER NOT NULL DEFAULT 1, error TEXT NOT NULL DEFAULT '', created_at INTEGER NOT NULL);
CREATE TABLE batches(id TEXT PRIMARY KEY, task_id TEXT NOT NULL REFERENCES tasks(id), call_id TEXT REFERENCES calls(id),
 first_id INTEGER NOT NULL, last_id INTEGER NOT NULL, changes INTEGER NOT NULL, at INTEGER NOT NULL);
CREATE TABLE audits(id INTEGER PRIMARY KEY, scope TEXT NOT NULL, requester TEXT NOT NULL, diagnostics TEXT NOT NULL, at INTEGER NOT NULL);
CREATE TABLE imports(source TEXT NOT NULL, scope TEXT NOT NULL, cursor INTEGER NOT NULL, PRIMARY KEY(source,scope));
PRAGMA user_version=1;
COMMIT;
